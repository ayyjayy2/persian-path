// Writes precache-manifest.js: every file the app needs offline, plus a content hash
// so the service worker picks up a new cache whenever any of them change.
// Run after changing app files or adding audio (Firebase deploys run it).
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

const root = path.join(__dirname, "..");
const SHELL = [
  "index.html", "app.js", "view.js", "learn-data.js", "sync.js", "backend.js", "auth-messages.js", "culture.js", "style.css", "manifest.json",
  "ds/classical.css",
  "vendor/preact-htm.js", "vendor/firebase.js",
  "vendor/leaflet/leaflet.js", "vendor/leaflet/leaflet.css",
];
const dirs = ["images", "vendor/leaflet/images", "audio"];

const files = [...SHELL];
for (const d of dirs) {
  for (const f of fs.readdirSync(path.join(root, d)).sort()) {
    if (!f.startsWith(".")) files.push(`${d}/${f}`);
  }
}

const hash = crypto.createHash("sha256");
for (const f of files) hash.update(f).update(fs.readFileSync(path.join(root, f)));
const version = hash.digest("hex").slice(0, 12);

// Article photos live on Wikimedia; cache them up front too (best effort)
const culture = fs.readFileSync(path.join(root, "culture.js"), "utf8");
const remote = [...new Set(culture.match(/https:\/\/upload\.wikimedia\.org\/[^"'`\s)]+/g) || [])];

const out = `// GENERATED by scripts/build-precache.js — do not edit.
self.PRECACHE_VERSION = ${JSON.stringify(version)};
self.PRECACHE_FILES = ${JSON.stringify(["/", ...files.map(f => "/" + f)], null, 0)};
self.PRECACHE_REMOTE = ${JSON.stringify(remote, null, 0)};
`;
fs.writeFileSync(path.join(root, "precache-manifest.js"), out);
console.log(`precache ${version}: ${files.length + 1} files, ${remote.length} remote images`);
